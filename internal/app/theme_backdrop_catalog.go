// themeBackdropCategoryOf is the group a recipe is shown under; a recipe the catalogue does not know
// goes under the last-resort group.
func themeBackdropCategoryOf(name string) string {
	if c, ok := themeBackdropCategory[name]; ok {
		return c
	}
	return "Kleur & glans"
}

