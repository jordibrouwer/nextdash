//go:build ignore

// gen-asset-hashes walks static/ and writes asset_hashes_gen.go with
// precomputed content hashes for production builds (no runtime SHA256 per request).
//
// Usage: go run scripts/gen-asset-hashes.go
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"go/format"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	root := "static"
	if len(os.Args) > 1 {
		root = os.Args[1]
	}

	hashes := map[string]string{}
	err := filepath.WalkDir(root, func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return nil
		}
		rel, relErr := filepath.Rel(root, path)
		if relErr != nil {
			return nil
		}
		rel = filepath.ToSlash(rel)
		if !strings.HasSuffix(rel, ".css") && !strings.HasSuffix(rel, ".js") {
			return nil
		}
		sum, hashErr := hashFile(path)
		if hashErr != nil {
			return hashErr
		}
		hashes[rel] = sum
		return nil
	})
	if err != nil {
		fmt.Fprintf(os.Stderr, "gen-asset-hashes: %v\n", err)
		os.Exit(1)
	}

	keys := make([]string, 0, len(hashes))
	for k := range hashes {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	// Built in memory and run through go/format before it is written. Emitting
	// the map straight to the file left the keys unaligned, which is what made
	// `gofmt -l .` -- and with it the fmt-check CI job -- report a generated
	// file that nobody is supposed to edit by hand.
	var buf bytes.Buffer
	fmt.Fprintln(&buf, "// Code generated by scripts/gen-asset-hashes.go; DO NOT EDIT.")
	fmt.Fprintln(&buf, "package main")
	fmt.Fprintln(&buf)
	fmt.Fprintln(&buf, "var precomputedAssetHashes = map[string]string{")
	for _, k := range keys {
		fmt.Fprintf(&buf, "\t%q: %q,\n", k, hashes[k])
	}
	fmt.Fprintln(&buf, "}")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		fmt.Fprintf(os.Stderr, "gen-asset-hashes: %v\n", err)
		os.Exit(1)
	}

	if err := os.WriteFile("asset_hashes_gen.go", formatted, 0644); err != nil {
		fmt.Fprintf(os.Stderr, "gen-asset-hashes: %v\n", err)
		os.Exit(1)
	}
}

func hashFile(path string) (string, error) {
	f, err := os.Open(path)
	if err != nil {
		return "", err
	}
	defer f.Close()
	h := sha256.New()
	if _, err := io.Copy(h, f); err != nil {
		return "", err
	}
	return hex.EncodeToString(h.Sum(nil)[:6]), nil
}
